test('salary reminders begin on the 27th in Dubai and stop when paid',()=>{
  const reminder=require('./salary-reminder');
  const data={workers:[{id:'alice'}],payments:[]};
  assert.equal(reminder(data,new Date('2026-11-26T19:59:59Z')),null);
  assert.match(reminder(data,new Date('2026-11-26T20:00:00Z')).message,/due tomorrow/);
  assert.match(reminder(data,new Date('2026-11-27T20:00:00Z')).message,/due today/);
  assert.match(reminder(data,new Date('2026-11-28T20:00:00Z')).message,/was due/);
  data.payments.push({workerId:'alice',month:'2026-11'});
  assert.equal(reminder(data,new Date('2026-11-27T20:00:00Z')),null);
  assert.equal(reminder(data,new Date('2026-12-26T20:00:00Z')).month,'2026-12');
  assert.equal(reminder({workers:[]},new Date('2026-11-27T20:00:00Z')),null);
});
